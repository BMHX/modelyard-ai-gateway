export function translateZhInlineText(text: string): string {
  if (!text) {
    return text;
  }

  const exactMatch = zhExactTranslations[text];
  if (exactMatch) {
    return exactMatch;
  }

  const lowercasedMatch = zhInlineTranslationsLowercase.get(text.toLowerCase());
  if (lowercasedMatch) {
    return lowercasedMatch;
  }

  const colonMatch = text.match(/^([^:：]+):\s*(.+)$/);
  if (colonMatch) {
    const [, leftPart, rightPart] = colonMatch;
    const translatedLeftPart =
      zhExactTranslations[leftPart] ??
      zhInlineTranslationsLowercase.get(leftPart.toLowerCase()) ??
      leftPart;
    const translatedRightPart = translateZhInlineText(rightPart);

    if (translatedLeftPart !== leftPart || translatedRightPart !== rightPart) {
      return `${translatedLeftPart}：${translatedRightPart}`;
    }
  }

  if (text.includes(" · ")) {
    const parts = text.split(" · ");
    const translatedParts = parts.map((part) => translateZhInlineText(part));
    if (translatedParts.some((part, index) => part !== parts[index])) {
      return translatedParts.join(" · ");
    }
  }

  const environmentScopeWithRuntimeMatch = text.match(/^environment \/ (.+) \((development|staging|production)\)$/i);
  if (environmentScopeWithRuntimeMatch) {
    const [, name, runtime] = environmentScopeWithRuntimeMatch;
    const localizedName = translateZhInlineText(name);
    const localizedRuntime = translateZhInlineText(runtime);
    return localizedName === localizedRuntime ? `环境 / ${localizedRuntime}` : `环境 / ${localizedName} (${localizedRuntime})`;
  }

  if (text.includes(" / ")) {
    const parts = text.split(" / ");
    const translatedParts = parts.map((part) => translateZhInlineText(part));
    if (translatedParts.some((part, index) => part !== parts[index])) {
      return translatedParts.join(" / ");
    }
  }

  for (const translate of [...zhPatternTranslators, ...zhExtraPatternTranslators]) {
    const translated = translate(text);
    if (translated) {
      return translated;
    }
  }

  return text;
}
